import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { reviewCases as originalCases, type ReviewCase } from './cases';
import { reviewCasesBoundary } from './boundary-cases';
const labelPath = 'artifacts/evaluation/human-review/2026-09-08-round1/AI_ADJUDICATION.json';
const raw = readFileSync(labelPath, 'utf8');
const labels = JSON.parse(raw);
export const labelHash = createHash('sha256').update(raw).digest('hex');
export const labelVersion = labels.version;
const batch = Number(process.env.REVIEW_BATCH);
if (!Number.isInteger(batch) || batch < 1 || batch > 5) throw new Error('Set REVIEW_BATCH=1..5; each batch contains 12 fixed adjudicated cases.');
const originals = [...originalCases, ...reviewCasesBoundary];
if (labels.records.length !== 60 || new Set(labels.records.map((r: any) => r.caseId)).size !== 60) throw new Error('Invalid label inventory');
export const reviewCases: readonly ReviewCase[] = labels.records.slice((batch - 1) * 12, batch * 12).map((r: any) => {
 const c = originals.find(c => c.id === r.caseId);
 if (!c || !['passed','blocked','needs_human_review'].includes(r.reviewStatus)) throw new Error('Invalid adjudication');
 const hash = createHash('sha256').update(JSON.stringify(c.input)).digest('hex');
 if (hash !== r.inputHash || hash !== createHash('sha256').update(JSON.stringify(r.input)).digest('hex')) throw new Error('Frozen input changed');
 return { ...c, input: r.input, expected: r.reviewStatus };
});
