test('manual edits invalidate review and cannot publish stale approval', async ({ page }) => {
  await generateAmazon(page);
  await fixAndPass(page);
  await page.getByRole('button', { name: 'Edit in Listing Studio' }).click();
  await page.getByRole('button', { name: 'Edit copy' }).click();
  await page.getByRole('textbox', { name: 'Title', exact: true }).fill('FDA certified, guaranteed thermal performance');
  await page.getByRole('button', { name: 'Save revision' }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button', { name: 'Continue to Review' }).click();
  await expect(page.getByRole('button', { name: 'Publish', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Run Review', exact: true }).click();
  await expect(page.locator('.risk-issue')).toContainText('R002');
  await expect(page.getByRole('button', { name: 'Publish', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Apply Suggested Fix' }).click();
  await page.getByRole('button', { name: 'Run Review', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Publish', exact: true })).toBeEnabled();
});

test('mobile layout, source preview keyboard, empty states and invalid storage recovery', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('/');
  await expect(page.locator('.product-table tbody tr')).toHaveCount(10);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'artifacts/materials-mobile.png', fullPage: true });
  await page.getByRole('navigation', { name: 'Workspaces' }).getByRole('button', { name: 'Review & Publish' }).click();
  await expect(page.getByRole('heading', { name: 'Generate a listing before review' })).toBeVisible();
  await generateAmazon(page);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await fixAndPass(page);
  await page.getByRole('button', { name: 'Publish', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Amazon Listing Export Ready' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'artifacts/publish-mobile.png', fullPage: true });
  await page.getByRole('navigation', { name: 'Workspaces' }).getByRole('button', { name: 'Evidence & Facts' }).click();
  await page.getByRole('button', { name: /Supplier Spreadsheet.*View extracted result/ }).click();
  await expect(page.getByRole('dialog')).toContainText('Mock extracted result');
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.evaluate(key => localStorage.setItem(key, '{broken'), KEY);
  await page.reload();
  await expect(page.locator('.product-table tbody tr')).toHaveCount(10);
  expect((await snapshot(page)).selectedSku).toBeNull();
});
