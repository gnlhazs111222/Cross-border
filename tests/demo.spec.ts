import { expect, test, type Page } from './fixtures';
import { mkdir } from 'node:fs/promises';

const HERO = 'LM-KT-BTL-001-BLK-500';
const KEY = 'prismlaunch.demo.v1';
const snapshot = (page: Page) => page.evaluate(key => JSON.parse(localStorage.getItem(key)!), KEY);
async function start(page: Page) {
  await page.goto('/');
  await expect(page.getByRole('button', { name: 'Reset Demo', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: 'Reset Demo', exact: true }).click();
  await expect(page.locator('.state-indicator')).toHaveText('Ready to start');
  await expect(page.locator('.product-table tbody tr')).toHaveCount(10);
  await page.getByRole('button', { name: 'Create Demo Task', exact: true }).click();
  await expect(page.getByTestId('recommendation-1')).toContainText(HERO);
  await expect(page.getByTestId('recommendation-1').locator('.match-score')).toHaveText('94/100');
  await page.getByTestId('recommendation-1').getByRole('button', { name: 'Select SKU', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'FactCard V1', exact: true })).toBeVisible();
}
async function generateAmazon(page: Page) {
  await start(page);
  const before = (await snapshot(page)).v1;
  await page.getByRole('button', { name: 'Analyze Evidence', exact: true }).first().click();
  await expect(page.getByRole('button', { name: 'Analyzing product evidence...' })).toBeVisible();
  await expect(page.locator('.suggested-price>strong')).toHaveText('USD 19.99');
  const after = await snapshot(page);
  expect(after.v1).toEqual(before);
  expect(after.v2.facts.length).toBeGreaterThan(after.v1.facts.length);
  await page.getByRole('button', { name: 'Continue to Listing Studio' }).click();
  await page.getByRole('button', { name: 'Generate Amazon Listing' }).click();
  await expect(page.locator('.listing-copy')).toContainText('100% leakproof');
  await expect(page.locator('.listing-copy')).not.toContainText(/Supplier cost|Declared value|Shipping|Duty|8\.20|3\.10/);
}
async function fixAndPass(page: Page) {
  await page.getByRole('button', { name: 'Continue to Review' }).click();
  await expect(page.getByRole('button', { name: 'Publish', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Run Review', exact: true }).click();
  await expect(page.locator('.risk-issue')).toContainText('R001');
  await expect(page.locator('.risk-issue')).toContainText('No verified evidence supports an absolute leakproof claim.');
  await expect(page.getByRole('button', { name: 'Publish', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Apply Suggested Fix', exact: true }).click();
  await expect(page.locator('.listing-copy')).not.toContainText('100% leakproof');
  await expect(page.getByRole('button', { name: 'Publish', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Run Review', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Review Passed', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Publish', exact: true })).toBeEnabled();
}

test('P0 complete: Amazon risk block, human fix, review, mock publish, CSV, reload and reset', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await mkdir('artifacts', { recursive: true });
  await page.goto('/');
  await expect(page.locator('.product-table tbody tr')).toHaveCount(10);
  await page.screenshot({ path: 'artifacts/materials-desktop.png', fullPage: true });
  await generateAmazon(page);
  await page.locator('.fact-sources summary').click();
  await expect(page.locator('.source-facts')).toContainText('Source: Packaging Image');
  await page.screenshot({ path: 'artifacts/listing-studio.png', fullPage: true });
  await page.getByRole('button', { name: 'Continue to Review' }).click();
  await page.getByRole('button', { name: 'Run Review', exact: true }).click();
  await expect(page.locator('.risk-issue')).toContainText('R001');
  await page.screenshot({ path: 'artifacts/review-blocked.png', fullPage: true });
  await page.reload();
  await expect(page.locator('.risk-issue')).toContainText('R001');
  await expect(page.getByRole('button', { name: 'Publish', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Apply Suggested Fix', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Publish', exact: true })).toBeDisabled();
  await expect(page.locator('.listing-copy')).toContainText('Secure screw-top lid designed for everyday carrying.');
  await page.getByRole('button', { name: 'Run Review', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Review Passed', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Publish', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: 'Publish', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Publishing...' })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Amazon Listing Export Ready' })).toBeVisible();
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export Amazon CSV' }).click();
  const download = await downloadEvent;
  expect(download.suggestedFilename()).toContain(HERO);
  await download.saveAs('artifacts/amazon-demo.csv');
  const stream = await download.createReadStream();
  const chunks = []; for await (const chunk of stream!) chunks.push(chunk);
  const csv = Buffer.concat(chunks).toString('utf8');
  expect(csv).toContain('19.99'); expect(csv).toContain(HERO); expect(csv).not.toContain('100% leakproof');
  expect(csv).not.toMatch(/supplier.?cost|declared.?value|shipping|duty/i);
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Amazon Listing Export Ready' })).toBeVisible();
  await page.screenshot({ path: 'artifacts/publish-success.png', fullPage: true });
  const completed = await snapshot(page);
  for (const stage of ['initial', 'materials_ready', 'task_created', 'sku_selected', 'evidence_analyzed', 'pricing_ready', 'listing_generated', 'review_blocked', 'review_passed', 'published']) expect(completed.history).toContain(stage);
  await page.getByRole('button', { name: 'Reset Demo', exact: true }).click();
  await expect(page.locator('.product-table tbody tr')).toHaveCount(10);
  expect((await snapshot(page)).task).toBeNull();
  expect((await snapshot(page)).listings).toEqual({});
  expect(errors).toEqual([]);
});

